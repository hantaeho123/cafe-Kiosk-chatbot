def format_documents(hits, sold_out=()):
    if not hits:
        return "(검색된 문서 없음)"
    return "\n\n".join(
        f"[문서 {i}] {h.doc['title']} ({DOC_TYPES.get(h.doc['type'], h.doc['type'])})"
        + (" — 지금 품절" if h.doc["metadata"].get("menu_id") in sold_out else "")
        + f"\n문서 ID: {h.doc['id']}\n{h.doc['text']}"
        for i, h in enumerate(hits, 1))


def realtime_state(session):
    """키오스크가 그때그때 넘기는 값: 품절, 지금 주문, 확인을 기다리는 변경안, POS 가 계산한 금액, 결제 상태."""
    sold_out = session.stock.names() if session.stock else []
    lines = ["품절 메뉴: " + (", ".join(sold_out) or "없음"), session.order.summary_text()]
    pending = session.pending_text()
    if pending:
        kind = "직전 변경 되돌리기" if session.draft_undo else "주문 변경"
        lines.append(f"확인을 기다리는 변경안({kind}). 손님이 화면에서 [확인]을 누르기 전이라 아직 주문에 반영되지 않았다:\n{pending}\n"
                     "  (손님이 말로 동의만 하면 도구를 다시 부르지 말고, 대화창 아래의 [변경 확인하기]로 확인 화면을 열어 [확인]을 눌러 달라고 "
                     "안내한다. 내용을 고치려 할 때만 도구를 쓴다.)")
    else:
        lines.append("확인을 기다리는 변경안: 없음")
    shown = getattr(session, "shown", [])
    lines.append("직전에 안내한 메뉴(순서대로): " + (" ".join(f"{i}) {name}" for i, name in enumerate(shown, 1)) or "없음"))
    return "\n".join(lines)


def _example_name(session, language):
    """그 언어의 메뉴 이름 예시(타로 밀크티). 예시가 영어면 중국어·일본어 답변에서도 영어 이름을 쓰는 일이 있었다."""
    menu, _ = session.catalog.resolve("타로 밀크티")
    names = session.catalog.names(menu) if menu else {}
    return names.get(language) or names.get("en") or "Taro Milk Tea"


def turn_message(session, hits, user_text, warnings=()):
    """이번 턴의 손님 메시지. 실시간 상태와 검색 문서를 붙여 모델에게 보낸다 (강의의 AUGMENT 단계)."""
    # 손님 글에 태그가 들어 있어도 구획이 깨지지 않게 꺾쇠를 바꿔 둔다.
    safe = user_text.replace("<", "‹").replace(">", "›")
    sold_out = set(session.stock.ids()) if session.stock else set()
    language = session.language
    events = "<화면조작>\n" + "\n".join(f"- {e}" for e in session.events) + "\n</화면조작>\n\n" if session.events else ""
    if warnings:  # 손님 말에서 코드가 찾은 문제: 서로 부딪치는 표현, 없는 사이즈
        events += "<주의>\n" + "\n".join(f"- {w}" for w in warnings) + "\n</주의>\n\n"
    return (f"<실시간상태>\n{realtime_state(session)}\n</실시간상태>\n\n{events}"
            f"<참고문서>\n{format_documents(hits, sold_out)}\n</참고문서>\n\n"
            "<출력형식>기존 주문 처리·되묻기·주의사항 안내 지침을 먼저 따릅니다. 답변 끝에는 "
            "<answer_sources>[참고한 문서 ID의 JSON 문자열 목록]</answer_sources>를 붙입니다. "
            "참고한 검색 문서가 없으면 <answer_sources>[]</answer_sources>입니다.</출력형식>\n\n"
            f"<응답언어>{LANGUAGES[language]}{'' if language == 'ko' else FOREIGN_NAME_RULE.format(example=_example_name(session, language)) + button_names(language)}</응답언어>\n\n"
            f"<손님>\n{safe}\n</손님>")
